export async function getAllArticles(): Promise<ArticleData[]> {
  try {
    const dbArticles = await prisma.article.findMany({
      where: { isPublished: true },
      orderBy: { createdAt: "desc" },
    });

    if (dbArticles && dbArticles.length > 0) {
      return dbArticles.map((art) => ({
        id: art.id,
        slug: art.slug,
        title: art.title,
        summary: art.summary,
        content: art.content,
        category: art.category,
        tags: art.tags ? art.tags.split(",").map((t) => t.trim()).filter(Boolean) : [],
        readTime: art.readTime,
        date: new Intl.DateTimeFormat("fa-IR", { dateStyle: "medium" }).format(art.createdAt),
        image: art.image,
        author: art.authorName,
        views: art.views,
        badgeColor: getBadgeColor(art.category),
      }));
    }
  } catch (error) {
    console.error("Error loading articles from DB, falling back to static:", error);
  }

  return INITIAL_ARTICLES;
}

export async function getArticleBySlug(slug: string): Promise<ArticleData | null> {
  try {
    const dbArticle = await prisma.article.findUnique({
      where: { slug },
    });

    if (dbArticle) {
      // Increment views count non-blockingly
      prisma.article.update({
        where: { slug },
        data: { views: { increment: 1 } },
      }).catch(() => {});

      return {
        id: dbArticle.id,
        slug: dbArticle.slug,
        title: dbArticle.title,
        summary: dbArticle.summary,
        content: dbArticle.content,
        category: dbArticle.category,
        tags: dbArticle.tags ? dbArticle.tags.split(",").map((t) => t.trim()).filter(Boolean) : [],
        readTime: dbArticle.readTime,
        date: new Intl.DateTimeFormat("fa-IR", { dateStyle: "medium" }).format(dbArticle.createdAt),
        image: dbArticle.image,
        author: dbArticle.authorName,
        views: dbArticle.views + 1,
        badgeColor: getBadgeColor(dbArticle.category),
      };
    }
  } catch (error) {
    console.error("Error fetching article by slug from DB:", error);
  }

  const fallback = INITIAL_ARTICLES.find((a) => a.slug === slug);
  return fallback || null;
}

export async function getRelatedArticles(currentSlug: string, category: string, limit = 3): Promise<ArticleData[]> {
  const all = await getAllArticles();
  return all
    .filter((a) => a.slug !== currentSlug)
    .sort((a, b) => (a.category === category ? -1 : 1))
    .slice(0, limit);
}

